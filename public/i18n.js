let activeLocale = "zh-CN";

export function normalizeLocale(value) {
  return String(value || "").toLowerCase().startsWith("en") ? "en" : "zh-CN";
}

export function detectLocale() {
  return normalizeLocale(globalThis.navigator?.language || "zh-CN");
}

export function setLocale(value) {
  activeLocale = normalizeLocale(value);
  if (globalThis.document) document.documentElement.lang = activeLocale;
  return activeLocale;
}

export function getLocale() {
  return activeLocale;
}

export function getTranslationKeys(locale) {
  const key = normalizeLocale(locale);
  return Object.keys(messages[key]);
}

export function t(key, values = {}) {
  const template = messages[activeLocale]?.[key] ?? messages.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : `{${name}}`,
  );
}

export function formatDateTime(value, options = {}) {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.valueOf())) return String(value);
  return new Intl.DateTimeFormat(activeLocale, {
    month: "numeric",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    ...options,
  }).format(date);
}
